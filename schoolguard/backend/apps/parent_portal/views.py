"""
parent_portal/views.py

Every view here does the same thing first: resolve request.user.parent_profile,
then filter to `parent_profile.children` -- never `Student.objects.all()`
scoped by school. A parent at School X should see nothing beyond their own
linked children, even though School X might have thousands of students.
Requesting a student ID that isn't one of theirs returns 404, the same
"structurally invisible" pattern used for tenant isolation everywhere else
in this project -- not a 403 that would confirm the ID belongs to someone.
"""

import io

from django.http import FileResponse
from django.shortcuts import get_object_or_404
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework.views import APIView
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from fees.models import Payment

from .permissions import IsParentUser
from .serializers import ChildDetailSerializer, ChildSummarySerializer


def _own_children_queryset(request):
    return request.user.parent_profile.children.select_related("school_class").prefetch_related("invoices__items")


class MyChildrenView(APIView):
    permission_classes = [IsAuthenticated, IsParentUser]

    def get(self, request):
        children = _own_children_queryset(request)
        return Response(ChildSummarySerializer(children, many=True).data)


class ChildDetailView(APIView):
    permission_classes = [IsAuthenticated, IsParentUser]

    def get(self, request, student_id):
        student = get_object_or_404(_own_children_queryset(request), id=student_id)
        return Response(ChildDetailSerializer(student).data)


class ReceiptDownloadView(APIView):
    permission_classes = [IsAuthenticated, IsParentUser]

    def get(self, request, payment_id):
        own_children_ids = request.user.parent_profile.children.values_list("id", flat=True)
        payment = get_object_or_404(
            Payment.objects.select_related("invoice__student", "invoice__term", "receipt", "invoice__school"),
            id=payment_id,
            invoice__student_id__in=own_children_ids,
        )

        pdf_bytes = _render_receipt_pdf(payment)
        filename = f"receipt-{payment.receipt.receipt_number}.pdf" if hasattr(payment, "receipt") else f"payment-{payment.id}.pdf"
        return FileResponse(io.BytesIO(pdf_bytes), as_attachment=True, filename=filename, content_type="application/pdf")


def _render_receipt_pdf(payment: Payment) -> bytes:
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    left = 20 * mm
    y = height - 25 * mm

    school = payment.invoice.school
    student = payment.invoice.student
    receipt_number = payment.receipt.receipt_number if hasattr(payment, "receipt") else f"PAYMENT-{payment.id}"

    c.setFont("Helvetica-Bold", 16)
    c.drawString(left, y, school.name)
    y -= 8 * mm

    c.setFont("Helvetica", 10)
    c.drawString(left, y, "Official Payment Receipt")
    y -= 12 * mm

    c.setFont("Helvetica-Bold", 12)
    c.drawString(left, y, f"Receipt No: {receipt_number}")
    y -= 10 * mm

    c.setFont("Helvetica", 10)
    rows = [
        ("Student", f"{student.full_name} ({student.admission_number})"),
        ("Term", payment.invoice.term.name),
        ("Amount paid", f"KSh {payment.amount:,.2f}"),
        ("Method", payment.get_method_display()),
        ("Reference", payment.reference_number or "\u2014"),
        ("Date", payment.paid_at.strftime("%d %b %Y, %H:%M")),
        ("Status", payment.get_status_display()),
    ]
    for label, value in rows:
        c.drawString(left, y, f"{label}:")
        c.drawString(left + 45 * mm, y, str(value))
        y -= 7 * mm

    y -= 5 * mm
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(left, y, "Generated by SchoolGuard. This receipt reflects the payment as recorded at the time of issue.")

    c.showPage()
    c.save()
    return buffer.getvalue()
