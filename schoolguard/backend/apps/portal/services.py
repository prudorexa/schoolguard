"""
portal/services.py

`get_child_or_404` is the enforcement point every other function in this
module goes through: a parent can only ever see a Student that's actually
linked to them (via the same Student.parents m2m used everywhere else),
in their own school. There's no endpoint in this app that trusts a
student_id from the URL without checking that ownership first -- this is
the parent-portal equivalent of TenantScopedViewSetMixin, just scoped one
level narrower (not "your school", but "your specific children").
"""

from decimal import Decimal
from io import BytesIO

from django.shortcuts import get_object_or_404
from reportlab.lib.pagesizes import A5
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from fees.models import Invoice, Payment, Receipt
from students.models import Student


def get_children(user) -> "list[Student]":
    return list(
        Student.objects.filter(parents__user=user, school=user.school)
        .select_related("school_class")
        .distinct()
        .order_by("first_name", "last_name")
    )


def get_child_or_404(*, user, student_id: int) -> Student:
    return get_object_or_404(
        Student.objects.filter(parents__user=user, school=user.school).distinct(),
        id=student_id,
    )


def child_fee_summary(student: Student) -> dict:
    """Lifetime summary -- 'since they arrived at school', not just the
    current term -- across every invoice ever issued for this student."""
    invoices = Invoice.objects.filter(student=student)
    total_billed = sum((inv.total_amount for inv in invoices), Decimal("0.00"))
    total_paid = sum((inv.amount_paid for inv in invoices), Decimal("0.00"))
    return {
        "total_billed": total_billed,
        "total_paid": total_paid,
        "balance": total_billed - total_paid,
    }


def get_child_invoices(student: Student):
    return Invoice.objects.filter(student=student).prefetch_related("items").order_by("-created_at")


def get_child_payment_history(student: Student):
    return (
        Payment.objects.filter(invoice__student=student, status="completed")
        .select_related("invoice", "invoice__term")
        .order_by("-paid_at")
    )


def get_receipt_for_parent_or_404(*, user, receipt_id: int) -> Receipt:
    """A receipt belongs to a payment, which belongs to an invoice, which
    belongs to a student -- ownership is checked across that whole chain,
    not assumed from the receipt_id alone."""
    return get_object_or_404(
        Receipt.objects.filter(payment__invoice__student__parents__user=user, school=user.school).select_related(
            "payment", "payment__invoice", "payment__invoice__student", "payment__invoice__term"
        ),
        id=receipt_id,
    )


def generate_receipt_pdf(receipt: Receipt) -> bytes:
    payment = receipt.payment
    invoice = payment.invoice
    student = invoice.student
    school = receipt.school

    buffer = BytesIO()
    page_size = A5
    c = canvas.Canvas(buffer, pagesize=page_size)
    width, height = page_size

    y = height - 20 * mm
    c.setFont("Helvetica-Bold", 14)
    c.drawString(15 * mm, y, school.name)
    y -= 8 * mm
    c.setFont("Helvetica-Bold", 12)
    c.drawString(15 * mm, y, "Payment Receipt")
    y -= 10 * mm

    c.setFont("Helvetica", 10)
    rows = [
        ("Receipt No.", receipt.receipt_number),
        ("Date", payment.paid_at.strftime("%d %b %Y, %H:%M")),
        ("Student", f"{student.full_name} (Adm. No. {student.admission_number})"),
        ("Term", invoice.term.name),
        ("Amount Paid", f"KSh {payment.amount:,.2f}"),
        ("Method", payment.get_method_display()),
        ("Reference", payment.reference_number or "—"),
        ("Invoice Total", f"KSh {invoice.total_amount:,.2f}"),
        ("Balance After Payment", f"KSh {invoice.balance:,.2f}"),
    ]
    for label, value in rows:
        c.setFont("Helvetica-Bold", 9)
        c.drawString(15 * mm, y, f"{label}:")
        c.setFont("Helvetica", 9)
        c.drawString(60 * mm, y, str(value))
        y -= 7 * mm

    y -= 5 * mm
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(15 * mm, y, "This receipt was generated by SchoolGuard and reflects a completed payment.")

    c.showPage()
    c.save()
    return buffer.getvalue()
